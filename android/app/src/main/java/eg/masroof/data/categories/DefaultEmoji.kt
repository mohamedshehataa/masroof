/** Emoji whose English or Arabic keywords contain every word of [query] (folded); an empty query lists all. */
fun searchEmoji(query: String): List<EmojiEntry> {
    val words = foldText(query).split(' ').filter { it.isNotEmpty() }
    if (words.isEmpty()) return EMOJI_CATALOG
    return EMOJI_CATALOG.filter { e ->
        val hay = "${foldText("${e.keywordsEn} ${e.keywordsAr}")} ${e.emoji}"
        words.all { hay.contains(it) }
    }
}
