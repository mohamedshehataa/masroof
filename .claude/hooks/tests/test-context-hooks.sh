#!/usr/bin/env bash
# REQ-OPS-006 inject-context, REQ-OPS-008 budget-check, REQ-OPS-009 snapshot-progress.
# shellcheck source=lib-test.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib-test.sh"

P="$(make_temp_repo)"
mkdir -p "$P/docs/backlog/EPIC-01" "$P/.claude"
cp "$REPO_DIR/.claude/state.example.json" "$P/.claude/state.example.json"
{ echo "# Progress"; for i in $(seq 1 30); do echo "2026-10-23 10:$i P0 SDLC bootstrap INFO line $i"; done; } > "$P/docs/PROGRESS.md"
printf '# Esc\n## Open\n- [ ] **OWNER-001** key\n- [ ] **OWNER-002** repo\n## Resolved\n- [x] old\n' > "$P/docs/ESCALATIONS.md"
printf '# CLAUDE\n## Invariants\n- Money is minor units\n- Cairo TZ\n## Workflow\n- not an invariant\n' > "$P/CLAUDE.md"
printf -- '---\nid: STORY-001\nstatus: READY\n---\n' > "$P/docs/backlog/EPIC-01/STORY-001.md"
printf -- '---\nid: STORY-002\nstatus: DONE\n---\n' > "$P/docs/backlog/EPIC-01/STORY-002.md"
export CLAUDE_PROJECT_DIR="$P"
jq '.phase=2 | .story="STORY-001" | .stage="implement" | .loop_count=1' "$MASROOF_STATE_FILE" > "$MASROOF_STATE_FILE.tmp" && mv "$MASROOF_STATE_FILE.tmp" "$MASROOF_STATE_FILE"

echo "-- inject-context (REQ-OPS-006)"
run_hook inject-context.sh "$(json_session_start compact)"; assert_allowed "REQ-OPS-006 exits 0"
assert_contains "$OUT" "Phase: 2" "REQ-OPS-006 prints phase"
assert_contains "$OUT" "STORY-001" "REQ-OPS-006 prints active story"
assert_contains "$OUT" "implement" "REQ-OPS-006 prints stage"
assert_contains "$OUT" "1/3" "REQ-OPS-006 prints loop counter"
assert_contains "$OUT" "line 30" "REQ-OPS-006 prints the tail of PROGRESS.md"
assert_not_contains "$OUT" "line 5 " "REQ-OPS-006 limits PROGRESS.md to the last 20 lines"
assert_contains "$OUT" "Open escalations (2)" "REQ-OPS-006 counts open escalations"
assert_not_contains "$OUT" "old" "REQ-OPS-006 omits resolved escalations"
assert_contains "$OUT" "Money is minor units" "REQ-OPS-006 prints invariants"
assert_not_contains "$OUT" "not an invariant" "REQ-OPS-006 stops at the next heading"
assert_contains "$OUT" "READY 1" "REQ-OPS-006 counts READY stories"
assert_contains "$OUT" "DONE 1" "REQ-OPS-006 counts DONE stories"
assert_contains "$OUT" "SessionStart: compact" "REQ-OPS-006 echoes the source"
assert_eq "$(printf '%s' "$OUT" | wc -c | tr -d ' ' | awk '{print ($1 < 10000) ? "small" : "big"}')" "small" "REQ-OPS-006 output stays under the 10k context cap"

echo "-- snapshot-progress (REQ-OPS-009)"
run_hook snapshot-progress.sh "$(json_precompact auto)"; assert_allowed "REQ-OPS-009 exits 0"
assert_contains "$(jq -r .last_compact_trigger "$MASROOF_STATE_FILE")" "auto" "REQ-OPS-009 records trigger"
assert_contains "$(jq -r .last_compact "$MASROOF_STATE_FILE")" "T" "REQ-OPS-009 records timestamp"
assert_eq "$(jq -r .story "$MASROOF_STATE_FILE")" "STORY-001" "REQ-OPS-009 keeps existing state"
assert_eq "$(find "$MASROOF_STATE_DIR/snapshots" -name 'state-*.json' | wc -l | tr -d ' ')" "1" "REQ-OPS-009 writes one snapshot file"

echo "-- budget-check (REQ-OPS-008)"
M="$TMP_ROOT/metrics.md"
mk_metrics() { printf '# M\n| metric | value |\n|---|---|\n| AI spend (USD) | %s |\n' "$1" > "$M"; }
mk_metrics 350; MASROOF_METRICS_FILE="$M" MASROOF_AI_BUDGET_USD=300 run_hook budget-check.sh "$(json_prompt)"; assert_allowed "REQ-OPS-008 never blocks"
assert_contains "$OUT" "BUDGET EXCEEDED" "REQ-OPS-008 warns when over budget"
assert_contains "$OUT" "350" "REQ-OPS-008 names the spend"
mk_metrics 250; MASROOF_METRICS_FILE="$M" MASROOF_AI_BUDGET_USD=300 run_hook budget-check.sh "$(json_prompt)"; assert_contains "$OUT" "80%" "REQ-OPS-008 soft warning above 80%"
mk_metrics 12.5; MASROOF_METRICS_FILE="$M" MASROOF_AI_BUDGET_USD=300 run_hook budget-check.sh "$(json_prompt)"; assert_eq "$OUT" "" "REQ-OPS-008 silent when well under budget"
printf 'SDLC_AI_BUDGET_USD=10   # comment\n' > "$P/.env.example"
mk_metrics 11; MASROOF_METRICS_FILE="$M" run_hook budget-check.sh "$(json_prompt)"; assert_contains "$OUT" "EXCEEDED" "REQ-OPS-008 reads budget from .env.example"
printf 'SDLC_AI_BUDGET_USD=1000\n' > "$P/.env"
mk_metrics 11; MASROOF_METRICS_FILE="$M" run_hook budget-check.sh "$(json_prompt)"; assert_eq "$OUT" "" "REQ-OPS-008 .env overrides .env.example"
rm -f "$M"; MASROOF_METRICS_FILE="$M" run_hook budget-check.sh "$(json_prompt)"; assert_allowed "REQ-OPS-008 missing metrics file passes silently"
finish
