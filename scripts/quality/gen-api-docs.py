#!/usr/bin/env python3
"""Render contracts/openapi.yaml into docs/API.md (deterministic: no timestamps, contract order).

Usage: gen-api-docs.py [--contract contracts/openapi.yaml] [--out docs/API.md]
`make docs-api` runs it; `make check` re-runs it and fails on `git diff --exit-code docs/API.md`.
"""
import argparse
import sys
from pathlib import Path

import yaml

METHODS = ("get", "put", "post", "delete", "patch")


def type_of(schema):
    """A short human type for a schema node."""
    if not isinstance(schema, dict):
        return "any"
    if "$ref" in schema:
        return "`%s`" % schema["$ref"].rsplit("/", 1)[-1]
    for key in ("oneOf", "anyOf"):
        if key in schema:
            return " or ".join(type_of(s) for s in schema[key])
    t = schema.get("type", "any")
    if isinstance(t, list):
        t = " or ".join(str(x) for x in t)
    if "enum" in schema:
        return "enum(%s)" % ", ".join(str(v) for v in schema["enum"])
    if t == "array":
        return "array of %s" % type_of(schema.get("items", {}))
    fmt = schema.get("format")
    return "%s (%s)" % (t, fmt) if fmt else str(t)


def cell(text):
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def render_schema(name, schema, out):
    out.append("### %s\n" % name)
    desc = schema.get("description")
    if desc:
        out.append(desc.strip() + "\n")
    props = schema.get("properties") or {}
    if props:
        required = set(schema.get("required") or [])
        out.append("| Field | Type | Required | Description |")
        out.append("|---|---|---|---|")
        for pname, pschema in props.items():
            out.append(
                "| `%s` | %s | %s | %s |"
                % (pname, cell(type_of(pschema)), "yes" if pname in required else "no",
                   cell(pschema.get("description") if isinstance(pschema, dict) else ""))
            )
        out.append("")
    else:
        out.append("Type: %s\n" % cell(type_of(schema)))


def render(spec):
    out = ["# Masroof API", "",
           "<!-- GENERATED by scripts/quality/gen-api-docs.py from contracts/openapi.yaml. Do not edit; run `make docs-api`. -->",
           ""]
    info = spec.get("info", {})
    out.append("%s (version %s)\n" % (info.get("title", "API"), info.get("version", "")))
    if info.get("description"):
        out.append(info["description"].strip() + "\n")
    tags = spec.get("tags") or []
    paths = spec.get("paths") or {}
    by_tag = {t["name"]: [] for t in tags}
    for path, item in paths.items():
        shared = item.get("parameters", [])
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            for tag in op.get("tags") or ["Other"]:
                by_tag.setdefault(tag, []).append((path, method, op, shared))
    out.append("## Operations\n")
    tag_desc = {t["name"]: t.get("description", "") for t in tags}
    for tag, ops in by_tag.items():
        out.append("## %s\n" % tag)
        if tag_desc.get(tag):
            out.append(tag_desc[tag] + "\n")
        for path, method, op, shared in ops:
            out.append("### `%s %s` - %s\n" % (method.upper(), path, op.get("summary", op.get("operationId", ""))))
            out.append("- operationId: `%s`" % op.get("operationId", ""))
            if op.get("x-req"):
                out.append("- Requirements: %s" % ", ".join(op["x-req"]))
            if op.get("security") == []:
                out.append("- Auth: none")
            out.append("")
            if op.get("description"):
                out.append(op["description"].strip() + "\n")
            params = list(shared) + list(op.get("parameters") or [])
            if params:
                out.append("| Parameter | In | Type | Required |")
                out.append("|---|---|---|---|")
                for p in params:
                    if "$ref" in p:
                        name = p["$ref"].rsplit("/", 1)[-1]
                        p = (spec.get("components", {}).get("parameters", {}) or {}).get(name, {"name": name})
                    out.append("| `%s` | %s | %s | %s |" % (p.get("name"), p.get("in", ""),
                               cell(type_of(p.get("schema", {}))), "yes" if p.get("required") else "no"))
                out.append("")
            body = op.get("requestBody")
            if body:
                for ctype, media in (body.get("content") or {}).items():
                    out.append("Request body (`%s`): %s\n" % (ctype, cell(type_of(media.get("schema", {})))))
            responses = op.get("responses") or {}
            if responses:
                out.append("| Status | Description | Body |")
                out.append("|---|---|---|")
                for code, resp in responses.items():
                    if "$ref" in resp:
                        name = resp["$ref"].rsplit("/", 1)[-1]
                        resp = (spec.get("components", {}).get("responses", {}) or {}).get(name, {})
                    bodies = ", ".join(
                        "%s: %s" % (ct, type_of(m.get("schema", {})))
                        for ct, m in (resp.get("content") or {}).items())
                    out.append("| %s | %s | %s |" % (code, cell(resp.get("description")), cell(bodies)))
                out.append("")
    out.append("## Schemas\n")
    for name, schema in (spec.get("components", {}).get("schemas") or {}).items():
        render_schema(name, schema, out)
    return "\n".join(out).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--contract", default="contracts/openapi.yaml")
    ap.add_argument("--out", default="docs/API.md")
    args = ap.parse_args()
    spec = yaml.safe_load(Path(args.contract).read_text(encoding="utf-8"))
    text = render(spec)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d lines)" % (out, text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
