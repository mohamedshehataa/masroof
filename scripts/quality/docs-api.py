#!/usr/bin/env python3
"""Render docs/API.md from contracts/openapi.yaml (REQ-OPS-052). Deterministic: no timestamps, stable ordering.

  docs-api.py [--contract contracts/openapi.yaml] [--out docs/API.md]

Sections: conventions (the contract description), endpoints grouped by tag (method, path, operationId, x-req ids,
parameters, request body, responses) in contract tag order, then every component schema with its properties.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_of(schema: dict | None) -> str:
    """Short human type for a schema node."""
    if not schema:
        return "any"
    if "$ref" in schema:
        return f"[{ref_name(schema['$ref'])}](#schema-{ref_name(schema['$ref']).lower()})"
    for key in ("oneOf", "anyOf", "allOf"):
        if key in schema:
            return f"{key}(" + " | ".join(type_of(s) for s in schema[key]) + ")"
    t = schema.get("type", "object")
    if isinstance(t, list):
        t = " | ".join(str(x) for x in t)
    if t == "array":
        return f"array of {type_of(schema.get('items'))}"
    if "enum" in schema:
        return "enum(" + ", ".join(str(v) for v in schema["enum"]) + ")"
    fmt = schema.get("format")
    if t == "object" and isinstance(schema.get("additionalProperties"), dict):
        return f"map of {type_of(schema['additionalProperties'])}"
    return f"{t} ({fmt})" if fmt else str(t)


def one_line(text: object) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def content_types(body: dict | None) -> list[str]:
    out = []
    for media, spec in sorted(((body or {}).get("content") or {}).items()):
        out.append(f"`{media}` {type_of((spec or {}).get('schema'))}")
    return out


def resolve(spec: dict, node: dict) -> dict:
    """Follow a top-level components $ref (parameters, responses, requestBodies)."""
    seen = 0
    while isinstance(node, dict) and "$ref" in node and seen < 10:
        cur: object = spec
        for part in node["$ref"].lstrip("#/").split("/"):
            cur = cur[part]  # type: ignore[index]
        node = cur  # type: ignore[assignment]
        seen += 1
    return node


def render(spec: dict) -> str:
    info = spec.get("info", {})
    lines: list[str] = [
        "# Masroof API",
        "",
        "<!-- Generated by `make docs-api` from contracts/openapi.yaml. Do not edit by hand. -->",
        "",
        f"Version `{info.get('version', '')}`. Source of truth: `contracts/openapi.yaml`.",
        "",
    ]
    if info.get("description"):
        lines += [str(info["description"]).strip(), ""]

    tags = [t["name"] for t in spec.get("tags", [])]
    tag_desc = {t["name"]: t.get("description", "") for t in spec.get("tags", [])}
    by_tag: dict[str, list[tuple[str, str, dict]]] = {t: [] for t in tags}
    for path in sorted(spec.get("paths", {})):
        item = spec["paths"][path]
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            for tag in op.get("tags") or ["Untagged"]:
                by_tag.setdefault(tag, []).append((method, path, op))

    lines += ["## Endpoints", ""]
    for tag in by_tag:
        ops = by_tag[tag]
        if not ops:
            continue
        lines += [f"### {tag}", ""]
        if tag_desc.get(tag):
            lines += [one_line(tag_desc[tag]), ""]
        for method, path, op in sorted(ops, key=lambda o: (o[1], METHODS.index(o[0]))):
            lines += [f"#### `{method.upper()} {path}` - {op.get('operationId', '(no operationId)')}", ""]
            if op.get("summary"):
                lines += [one_line(op["summary"]), ""]
            if op.get("x-req"):
                lines += ["Requirements: " + ", ".join(f"`{r}`" for r in op["x-req"]), ""]
            secured = op.get("security")
            if secured == []:
                lines += ["Authentication: none.", ""]
            params = [resolve(spec, p) for p in (spec["paths"][path].get("parameters") or []) + (op.get("parameters") or [])]
            if params:
                lines += ["| Parameter | In | Required | Type |", "|---|---|---|---|"]
                for p in params:
                    lines.append(
                        f"| `{p.get('name')}` | {p.get('in')} | {'yes' if p.get('required') else 'no'} | {type_of(p.get('schema'))} |"
                    )
                lines.append("")
            body = resolve(spec, op["requestBody"]) if op.get("requestBody") else None
            if body:
                lines += ["Request body: " + "; ".join(content_types(body)), ""]
            lines += ["| Status | Description | Body |", "|---|---|---|"]
            for status in sorted(op.get("responses", {}), key=str):
                resp = resolve(spec, op["responses"][status])
                lines.append(
                    f"| {status} | {one_line(resp.get('description'))} | {'; '.join(content_types(resp)) or '-'} |"
                )
            lines.append("")

    schemas = (spec.get("components") or {}).get("schemas") or {}
    lines += ["## Schemas", ""]
    for name in sorted(schemas):
        sch = schemas[name]
        lines += [f'<a id="schema-{name.lower()}"></a>', f"### {name}", ""]
        if sch.get("description"):
            lines += [one_line(sch["description"]), ""]
        props = sch.get("properties") or {}
        if props:
            required = set(sch.get("required") or [])
            lines += ["| Property | Type | Required | Description |", "|---|---|---|---|"]
            for pname in props:
                p = props[pname]
                lines.append(
                    f"| `{pname}` | {type_of(p)} | {'yes' if pname in required else 'no'} | {one_line(p.get('description'))} |"
                )
            lines.append("")
        else:
            lines += [f"Type: {type_of(sch)}", ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--contract", default="contracts/openapi.yaml")
    ap.add_argument("--out", default="docs/API.md")
    args = ap.parse_args(argv)
    spec = yaml.safe_load(Path(args.contract).read_text(encoding="utf-8"))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(spec), encoding="utf-8", newline="\n")
    print(f"docs-api: wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
